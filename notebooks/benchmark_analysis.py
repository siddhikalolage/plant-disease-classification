"""Benchmark analysis helper script

Usage:
    python notebooks/benchmark_analysis.py --input benchmark_results.csv --show

This script loads `benchmark_results.csv` generated by `scripts/run_benchmarks.py` and
produces plots comparing models on parameters, estimated size, inference latency, and
accuracy metrics.

It uses pandas, matplotlib, and seaborn.
"""
import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

sns.set(style="whitegrid")


def load_results(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    # cast numeric columns
    numeric_cols = [
        'parameters',
        'estimated_size_bytes',
        'average_latency_ms',
        'accuracy',
        'macro_f1',
        'weighted_f1',
        'top_3_accuracy',
    ]
    for c in numeric_cols:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors='coerce')
    return df


def summarize_best(df: pd.DataFrame) -> dict:
    best = {}
    if 'parameters' in df.columns:
        best['fewest_parameters'] = df.loc[df['parameters'].idxmin()].to_dict()
    if 'estimated_size_bytes' in df.columns:
        best['smallest_model'] = df.loc[df['estimated_size_bytes'].idxmin()].to_dict()
    if 'average_latency_ms' in df.columns:
        best['fastest_model'] = df.loc[df['average_latency_ms'].idxmin()].to_dict()
    for metric in ('accuracy', 'macro_f1', 'weighted_f1', 'top_3_accuracy'):
        if metric in df.columns:
            best[f'best_{metric}'] = df.loc[df[metric].idxmax()].to_dict()
    return best


def plot_bars(df: pd.DataFrame, column: str, title: str, ylabel: str, log_scale: bool = False):
    plt.figure(figsize=(8, 4))
    df_sorted = df.sort_values(column, ascending=False)
    ax = sns.barplot(x='model_name', y=column, data=df_sorted, palette='muted')
    ax.set_title(title)
    ax.set_xlabel('Model')
    ax.set_ylabel(ylabel)
    if log_scale:
        ax.set_yscale('log')
    plt.xticks(rotation=45)
    plt.tight_layout()
    return ax.get_figure()


def plot_grouped_metrics(df: pd.DataFrame, metrics: list[str], title: str):
    subset = df[['model_name'] + metrics].melt(id_vars='model_name', value_vars=metrics, var_name='metric', value_name='value')
    plt.figure(figsize=(10, 5))
    ax = sns.barplot(x='model_name', y='value', hue='metric', data=subset)
    ax.set_title(title)
    plt.xticks(rotation=45)
    plt.legend(title='Metric')
    plt.tight_layout()
    return ax.get_figure()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', type=str, default='benchmark_results.csv')
    parser.add_argument('--show', action='store_true')
    parser.add_argument('--output-dir', type=str, default='notebooks/figures')
    args = parser.parse_args()

    path = Path(args.input)
    if not path.exists():
        raise FileNotFoundError(f"Input file not found: {path}")

    df = load_results(path)
    print('Loaded results:')
    print(df)

    best = summarize_best(df)
    print('\nBest by metric:')
    for k, v in best.items():
        print(f"- {k}: {v.get('model_name')} ({v.get('parameters', '')} params)")

    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    figs = []
    if 'parameters' in df.columns:
        figs.append((plot_bars(df, 'parameters', 'Model Parameter Count', 'Parameters', log_scale=True), 'parameters.png'))
    if 'estimated_size_bytes' in df.columns:
        figs.append((plot_bars(df, 'estimated_size_bytes', 'Estimated Model Size (bytes)', 'Bytes', log_scale=True), 'size.png'))
    if 'average_latency_ms' in df.columns:
        figs.append((plot_bars(df, 'average_latency_ms', 'Average Inference Latency (ms)', 'ms'), 'latency.png'))

    metric_list = [m for m in ('accuracy', 'macro_f1', 'weighted_f1', 'top_3_accuracy') if m in df.columns]
    if metric_list:
        figs.append((plot_grouped_metrics(df, metric_list, 'Evaluation Metrics by Model'), 'metrics.png'))

    for fig, name in figs:
        out_path = out_dir / name
        fig.savefig(out_path)
        print(f'Saved figure: {out_path}')

    if args.show:
        plt.show()


if __name__ == '__main__':
    main()
